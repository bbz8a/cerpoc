const { login, snap, BASE } = require('./19-phase2-cer');
(async () => {
  process.env.TAG = 'x';
  const { browser, page } = await login('cer.admin');
  await page.goto(BASE + '/cer/register/installations/new');
  const main = page.getByRole('main');
  const unit = main.getByRole('combobox', { name: 'Unit' });
  await unit.locator('option', { hasText: 'GridCell' }).first().waitFor({ state: 'attached' });
  await unit.selectOption(await unit.locator('option', { hasText: 'GridCell' }).first().getAttribute('value'));
  const inst = main.getByRole('combobox', { name: /^Installer/ });
  console.log('INSTALLERS w/ Grid:', await inst.locator('option').evaluateAll(o => o.map(x => x.textContent).filter(t => /grid/i.test(t))));
  await inst.selectOption({ index: 1 }); console.log('installer', await inst.locator('option:checked').textContent());
  await main.getByRole('textbox', { name: /^NMI/ }).fill('4001234567');
  await main.getByRole('textbox', { name: 'Address line 1' }).fill('1 Test Street');
  await main.getByRole('textbox', { name: 'Suburb' }).fill('Canberra');
  await main.getByRole('combobox', { name: 'State' }).selectOption('ACT');
  await main.getByRole('textbox', { name: 'Postcode' }).fill('2600');
  await page.getByText('Validating installation attributes').waitFor();
  console.log('grid opts', await main.getByRole('combobox', { name: 'grid_connected' }).locator('option').evaluateAll(o => o.map(x => `${x.value}|${x.textContent}`)));
  page.on('response', async r => { if (r.url().includes('/api/') && r.request().method() === 'POST') console.log('POST', r.status(), r.url(), (await r.text().catch(() => '')).slice(0, 800)); });
  await main.getByRole('button', { name: 'Record installation' }).click();
  await page.waitForTimeout(4000);
  await snap(page, 'missing-grid');
  await main.getByRole('combobox', { name: 'grid_connected' }).selectOption({ index: 1 });
  await main.getByRole('button', { name: 'Record installation' }).click();
  await page.waitForTimeout(4000);
  await snap(page, 'duplicate');
  await page.goto(BASE + '/cer/register'); 
  await page.getByRole('navigation', { name: 'Register sections' }).getByRole('button', { name: 'Rejected submissions' }).click();
  await page.waitForTimeout(4000);
  await snap(page, 'rejected');
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
